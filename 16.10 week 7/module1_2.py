@cuda.jit
def atomic_cas_float_add(arr, index, val):
    i = cuda.grid(1)

    if i < val.size: # Assuming val is an array of adds
        v = val[i]

        # Read current
        old = arr[index]
        assumed = old

        # CAS loop
        while True:
            assumed = old
            sum_val = numba.cuda.int_as_float(numba.cuda.float_as_int(assumed) + numba.cuda.float_as_int(v)) # Emulated float math

            # Use atomic_cas on the int representation
            old_int = cuda.atomic.cas(arr, index, numba.cuda.float_as_int(assumed), numba.cuda.float_as_int(sum_val))
            old = numba.cuda.int_as_float(old_int)

            if old_int == numba.cuda.float_as_int(assumed):
                break

