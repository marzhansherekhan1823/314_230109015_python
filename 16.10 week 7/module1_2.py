@cuda.jit
def sparse_dot_product_atomic(indices, values, dense_vec, result):
    start = cuda.grid(1)
    stride = cuda.gridsize(1)

    # Grid-stride loop over non-zero elements
    for k in range(start, indices.size, stride):
        idx = indices[k]
        val = values[k]

        prod = val * dense_vec[idx]

        # Accumulate to single scalar
        cuda.atomic.add(result, 0, prod)