    pageable_time = time.time() - start_time

    # Pinned memory
    pinned_arr = cuda.pinned_array(num_elements, dtype=np.float32)
    np.copyto(pinned_arr, pageable_arr)
    start_time = time.time()
    d_pinned = cuda.to_device(pinned_arr)
