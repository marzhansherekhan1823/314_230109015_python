# Assuming a block size of 256 and max radius of 16 for shared memory allocation
BLOCK_SIZE = 256
MAX_RADIUS = 16

@cuda.jit
def stencil_1d_shared(in_arr, out_arr, radius):
    s_arr = cuda.shared.array(shape=(BLOCK_SIZE + 2 * MAX_RADIUS), dtype=numba.float32)

    tid = cuda.threadIdx.x
    gid = cuda.grid(1)

    # Global index offset by radius for the shared memory mapping
    s_idx = tid + radius

    if gid < in_arr.size:
        s_arr[s_idx] = in_arr[gid]

        # Halo loads for boundaries
        if tid < radius:
            # Left halo
            if gid >= radius:
                s_arr[s_idx - radius] = in_arr[gid - radius]
            else:
                s_arr[s_idx - radius] = in_arr[0] # Clamp to edge

            # Right halo
            if gid + BLOCK_SIZE < in_arr.size:
                s_arr[s_idx + BLOCK_SIZE] = in_arr[gid + BLOCK_SIZE]
            else:
                s_arr[s_idx + BLOCK_SIZE] = in_arr[in_arr.size - 1] # Clamp to edge

    cuda.syncthreads()

    if gid < in_arr.size:
        # Compute moving average
        temp_sum = 0.0
        for j in range(-radius, radius + 1):
            temp_sum += s_arr[s_idx + j]
        out_arr[gid] = temp_sum / (2 * radius + 1)

