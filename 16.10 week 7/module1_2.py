from numba import cuda
import numba

BLOCK_SIZE = 1024

@cuda.jit
def scan_hillis_steele(x, out):
    s_in = cuda.shared.array(BLOCK_SIZE, dtype=numba.float32)
    s_out = cuda.shared.array(BLOCK_SIZE, dtype=numba.float32)

    tid = cuda.threadIdx.x
    if tid < x.size:
        s_in[tid] = x[tid]
    else:
        s_in[tid] = 0.0
    cuda.syncthreads()

    # Stride doubling (stride = 1, 2, 4, ... < blockDim.x)
    stride = 1
    while stride < cuda.blockDim.x:
        if tid >= stride:
            s_out[tid] = s_in[tid] + s_in[tid - stride]
        else:
            s_out[tid] = s_in[tid]
        cuda.syncthreads()

        # Ping-pong buffers
        s_in[tid] = s_out[tid]
        cuda.syncthreads()
        stride *= 2

    if tid < x.size:
        out[tid] = s_out[tid]

