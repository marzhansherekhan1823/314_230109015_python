TILE_DIM = 32

@cuda.jit
def transpose_bank_conflict_free(A, B):
    # Padding with +1 column (32, 33) to eliminate 32-way shared memory bank conflicts
    s_tile = cuda.shared.array((TILE_DIM, TILE_DIM + 1), dtype=numba.float32)

    x = cuda.blockIdx.x * TILE_DIM + cuda.threadIdx.x
    y = cuda.blockIdx.y * TILE_DIM + cuda.threadIdx.y

    if x < A.shape[0] and y < A.shape[1]:
        s_tile[cuda.threadIdx.y, cuda.threadIdx.x] = A[x, y]

    cuda.syncthreads()

    # Transposed indices for writing to global memory
    tr_x = cuda.blockIdx.y * TILE_DIM + cuda.threadIdx.x
    tr_y = cuda.blockIdx.x * TILE_DIM + cuda.threadIdx.y

    if tr_x < B.shape[0] and tr_y < B.shape[1]:
        B[tr_x, tr_y] = s_tile[cuda.threadIdx.x, cuda.threadIdx.y]

