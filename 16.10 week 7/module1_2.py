@cuda.jit
def reduction_argmax_shared(in_arr, block_max_vals, block_max_indices):
    s_vals = cuda.shared.array(BLOCK_SIZE, dtype=numba.float32)
    s_idxs = cuda.shared.array(BLOCK_SIZE, dtype=numba.int64)

    tid = cuda.threadIdx.x
    i = cuda.grid(1)

    if i < in_arr.size:
        s_vals[tid] = in_arr[i]
        s_idxs[tid] = i
    else:
        s_vals[tid] = -1e38 # small value
        s_idxs[tid] = -1

    cuda.syncthreads()

    stride = cuda.blockDim.x // 2
    while stride > 0:
        if tid < stride:
            if s_vals[tid + stride] > s_vals[tid]:
                s_vals[tid] = s_vals[tid + stride]
                s_idxs[tid] = s_idxs[tid + stride]
            elif s_vals[tid + stride] == s_vals[tid]:
                # Preserve earliest index on tie
                if s_idxs[tid + stride] < s_idxs[tid]:
                    s_idxs[tid] = s_idxs[tid + stride]
        cuda.syncthreads()
        stride >>= 1

    if tid == 0:
        block_max_vals[cuda.blockIdx.x] = s_vals[0]
        block_max_indices[cuda.blockIdx.x] = s_idxs[0]

