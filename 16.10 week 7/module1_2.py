BLOCK_SIZE = 256

@cuda.jit
def reduction_sum_shared(in_arr, block_sums):
    s_data = cuda.shared.array(BLOCK_SIZE, dtype=numba.float32)

    tid = cuda.threadIdx.x
    i = cuda.grid(1)

    s_data[tid] = in_arr[i] if i < in_arr.size else 0.0
    cuda.syncthreads()

    # Sequential addressing tree reduction
    stride = cuda.blockDim.x // 2
    while stride > 0:
        if tid < stride:
            s_data[tid] += s_data[tid + stride]
        cuda.syncthreads()
        stride >>= 1

    if tid == 0:
        block_sums[cuda.blockIdx.x] = s_data[0]

