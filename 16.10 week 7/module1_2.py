from numba import cuda
import numba

BLOCK_SIZE = 1024

@cuda.jit
def scan_blelloch_work_efficient(x, out):
    temp = cuda.shared.array(BLOCK_SIZE, dtype=numba.float32)
    tid = cuda.threadIdx.x

    temp[tid] = x[tid] if tid < x.size else 0.0
    cuda.syncthreads()

    # Up-Sweep (reduce)
    stride = 1
    while stride < cuda.blockDim.x:
        index = (tid + 1) * stride * 2 - 1
        if index < cuda.blockDim.x:
            temp[index] += temp[index - stride]
        stride *= 2
        cuda.syncthreads()

    if tid == 0:
        temp[cuda.blockDim.x - 1] = 0.0
    cuda.syncthreads()

    # Down-Sweep
    stride = cuda.blockDim.x // 2
    while stride > 0:
        index = (tid + 1) * stride * 2 - 1
        if index < cuda.blockDim.x:
            t = temp[index - stride]
            temp[index - stride] = temp[index]
            temp[index] += t
        stride //= 2
        cuda.syncthreads()

    # Convert to inclusive scan and write out
    if tid < x.size:
        out[tid] = temp[tid] + x[tid]

