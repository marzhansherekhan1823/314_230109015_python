@cuda.jit
def warp_reduce_sum_shfl(in_arr, out_arr):
    i = cuda.grid(1)
    val = in_arr[i] if i < in_arr.size else 0.0

    # In-warp sum reduction using shfl_down_sync with deltas 16, 8, 4, 2, 1
    val += cuda.shfl_down_sync(0xFFFFFFFF, val, 16)
    val += cuda.shfl_down_sync(0xFFFFFFFF, val, 8)
    val += cuda.shfl_down_sync(0xFFFFFFFF, val, 4)
    val += cuda.shfl_down_sync(0xFFFFFFFF, val, 2)
    val += cuda.shfl_down_sync(0xFFFFFFFF, val, 1)

    # Thread lane 0 in each warp holds warp sum
    lane_id = cuda.threadIdx.x % 32
    warp_id = cuda.threadIdx.x // 32

    if lane_id == 0:
        cuda.atomic.add(out_arr, 0, val)

