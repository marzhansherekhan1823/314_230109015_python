TILE_DIM = 16

@cuda.jit
def matmul_tiled_shared(A, B, C):
    sA = cuda.shared.array((TILE_DIM, TILE_DIM), dtype=numba.float32)
    sB = cuda.shared.array((TILE_DIM, TILE_DIM), dtype=numba.float32)

    x, y = cuda.grid(2)
    tx = cuda.threadIdx.x
    ty = cuda.threadIdx.y

    acc = 0.0
    # Loop over phase tiles
    for i in range((A.shape[1] + TILE_DIM - 1) // TILE_DIM):
        if x < A.shape[0] and (i * TILE_DIM + ty) < A.shape[1]:
            sA[tx, ty] = A[x, i * TILE_DIM + ty]
        else:
            sA[tx, ty] = 0.0

        if y < B.shape[1] and (i * TILE_DIM + tx) < B.shape[0]:
            sB[tx, ty] = B[i * TILE_DIM + tx, y]
        else:
            sB[tx, ty] = 0.0

        cuda.syncthreads()

        for j in range(TILE_DIM):
            acc += sA[tx, j] * sB[j, ty]

        cuda.syncthreads()

    if x < C.shape[0] and y < C.shape[1]:
        C[x, y] = acc

