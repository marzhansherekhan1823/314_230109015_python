NUM_BINS = 256

@cuda.jit
def histogram_privatized(data, bins_out, num_bins):
    s_bins = cuda.shared.array(NUM_BINS, dtype=numba.int32)

    tid = cuda.threadIdx.x
    i = cuda.grid(1)

    # Initialize private shared-memory bins
    if tid < num_bins:
        s_bins[tid] = 0
    cuda.syncthreads()

    # Accumulate locally
    if i < data.size:
        cuda.atomic.add(s_bins, data[i], 1)
    cuda.syncthreads()

    # Reduce to global bins
    if tid < num_bins:
        cuda.atomic.add(bins_out, tid, s_bins[tid])

